#!/usr/bin/env python3
"""Builds the desktop Omni Node archive for one OS from a kiroba/Omni-Daemon checkout.

    python scripts/package_desktop.py --daemon daemon --platform windows|linux|macos --out dist

Same approach as The-Omniverse .github/workflows/omni-node-windows.yml (which built the Windows zip
until Node 0.5.0): plain Python sources (the daemon, every omni_* module it imports, found by walking
imports with ast, plus the Tk shell omni_node_desktop and the shared core omni_node_core +
omni_node_words) and a launcher. Needs Python 3.12 on the computer. Adds NODE_VERSION and the generated
omni_node_version.py from this repo's single VERSION file, so the desktop shows the same Omni Node
version as the APK.

Output: dist/omni-node-windows-x64.zip, dist/omni-node-linux.tar.gz or dist/omni-node-macos.tar.gz.
"""
import argparse
import ast
import re
import shutil
import sys
import tarfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = {"windows": "omni-node-windows-x64.zip", "linux": "omni-node-linux.tar.gz", "macos": "omni-node-macos.tar.gz"}
ENTRY = ["omni_live_daemon_server", "omni_node_desktop", "omni_node_words", "omni_node_core"]

README_WINDOWS = (
    "Omni Node for Windows (pre-alpha) {v}\r\n\r\n"
    "Needs Python 3.12 from python.org (tick 'Add python.exe to PATH').\r\n"
    "Double-click 'Start Omni Node.cmd'. The first run installs cryptography, pystray and pillow for your user.\r\n"
    "It opens the same Omni Node screen as Android and starts the daemon. Close the window to keep it in the tray.\r\n"
    "Turn on 'Start when I sign in' to run it at sign-in (no admin needed).\r\n")
README_UNIX = (
    "Omni Node for {os} (pre-alpha) {v}\n\n"
    "Needs Python 3.12 with Tk. {os_hint}\n"
    "Run ./start-omni-node.sh. The first run installs cryptography (and pystray + pillow for a tray icon) for your\n"
    "user when pip allows it; otherwise install them with your package manager.\n"
    "It opens the same Omni Node screen as Android and starts the daemon.\n"
    "Turn on 'Start when I sign in' to run it at sign-in (no admin needed).\n")
OS_HINT = {"linux": "Debian/Ubuntu: sudo apt install python3 python3-tk python3-cryptography",
           "macos": "The python.org installer for macOS includes Tk."}
START_SH = """#!/bin/sh
# Omni Node (desktop): installs the optional packages once, then opens the window.
cd "$(dirname "$0")" || exit 1
PY="$(command -v python3.12 || command -v python3 || command -v python)"
if [ -z "$PY" ]; then echo "Python 3.12 is needed: see README.txt" >&2; exit 1; fi
"$PY" -c "import cryptography" 2>/dev/null || "$PY" -m pip install --user --quiet cryptography || true
"$PY" -c "import pystray, PIL" 2>/dev/null || "$PY" -m pip install --user --quiet pystray pillow 2>/dev/null || true
exec "$PY" omni_node_desktop.py "$@"
"""


def modules(src: Path) -> list:
    todo, seen = list(ENTRY), set()
    while todo:
        m = todo.pop()
        if m in seen or not (src / f"{m}.py").exists():
            continue
        seen.add(m)
        tree = ast.parse((src / f"{m}.py").read_text(encoding="utf-8"))
        for n in ast.walk(tree):
            names = [a.name for a in n.names] if isinstance(n, ast.Import) else (
                [n.module] if isinstance(n, ast.ImportFrom) and n.module else [])
            todo += [x.split(".")[0] for x in names if x.startswith("omni_")]
    missing = [m for m in ENTRY if m not in seen]
    if missing:
        sys.exit(f"daemon checkout lacks {missing} (needs Omni-Daemon v8.27.0+)")
    return sorted(seen)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--daemon", required=True, help="path to a kiroba/Omni-Daemon checkout")
    ap.add_argument("--platform", required=True, choices=sorted(ASSETS))
    ap.add_argument("--out", default="dist")
    ap.add_argument("--stage", default="omni-node", help="folder to assemble in (kept for the smoke test)")
    a = ap.parse_args(argv)
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        sys.exit(f"VERSION must be x.y.z, got {version!r}")
    src = Path(a.daemon) / "Admin"
    stage = Path(a.stage)
    shutil.rmtree(stage, ignore_errors=True)
    stage.mkdir(parents=True)
    for m in modules(src):
        shutil.copy(src / f"{m}.py", stage / f"{m}.py")
    (stage / "NODE_VERSION").write_text(version + "\n", encoding="utf-8")
    (stage / "omni_node_version.py").write_text(
        f'# Generated by scripts/package_desktop.py from VERSION. Do not edit.\nVERSION = "{version}"\n', encoding="utf-8")
    if a.platform == "windows":
        shutil.copy(src / "omni_node_desktop.pyw", stage / "Omni Node.pyw")
        (stage / "Start Omni Node.cmd").write_text(
            '@echo off\r\ncd /d "%~dp0"\r\npy -3 -m pip install --user --quiet cryptography pystray pillow\r\n'
            'start "" pyw -3 "Omni Node.pyw"\r\n', encoding="ascii")
        (stage / "README.txt").write_text(README_WINDOWS.format(v=version), encoding="utf-8")
    else:
        sh = stage / "start-omni-node.sh"
        sh.write_text(START_SH, encoding="utf-8")
        sh.chmod(0o755)
        (stage / "README.txt").write_text(
            README_UNIX.format(os="macOS" if a.platform == "macos" else "Linux", v=version, os_hint=OS_HINT[a.platform]),
            encoding="utf-8")
    print("packaged:", " ".join(sorted(p.name for p in stage.iterdir())))
    return 0


def archive(stage: Path, platform: str, out: Path) -> Path:
    """Zip (Windows) or tar.gz (keeps the launcher executable) of the staged folder, minus test leftovers."""
    out.mkdir(parents=True, exist_ok=True)
    dest = out / ASSETS[platform]
    files = [p for p in sorted(stage.rglob("*")) if p.is_file() and "__pycache__" not in p.parts
             and not p.name.startswith(("continuity_events.db", "d.log", "d.err")) and ".omni" not in p.parts]
    if platform == "windows":
        with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
            for p in files:
                z.write(p, p.relative_to(stage).as_posix())
    else:
        with tarfile.open(dest, "w:gz") as t:
            for p in files:
                info = t.gettarinfo(str(p), "omni-node/" + p.relative_to(stage).as_posix())
                info.mode = 0o755 if p.suffix == ".sh" else 0o644
                info.uid = info.gid = 0
                info.uname = info.gname = ""
                with open(p, "rb") as f:
                    t.addfile(info, f)
    return dest


def archive_version(path: Path) -> str:
    """NODE_VERSION inside a built archive (the publish job checks it equals VERSION)."""
    if path.suffix == ".zip":
        with zipfile.ZipFile(path) as z:
            return z.read("NODE_VERSION").decode().strip()
    with tarfile.open(path) as t:
        return t.extractfile("omni-node/NODE_VERSION").read().decode().strip()


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "archive":       # package_desktop.py archive <stage> <platform> <out>
        print(archive(Path(sys.argv[2]), sys.argv[3], Path(sys.argv[4])))
    elif len(sys.argv) > 1 and sys.argv[1] == "version":     # package_desktop.py version <archive>
        print(archive_version(Path(sys.argv[2])))
    else:
        sys.exit(main())
