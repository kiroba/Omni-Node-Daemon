#!/usr/bin/env bash
# Copies the daemon and the shared Node core from kiroba/Omni-Daemon into the app. One source of
# truth: the daemon, omni_node_core.py and omni_node_words.py are developed and tested there; this
# repo only packages them (plus the Kotlin shell around them).
#   scripts/fetch_daemon.sh [ref]     ref = tag, branch or commit (default: main)
set -euo pipefail
REF="${1:-main}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/app/src/main/python"
TMP="$(mktemp -d)"
git clone --quiet https://github.com/kiroba/Omni-Daemon.git "$TMP/daemon"
git -C "$TMP/daemon" checkout --quiet "$REF"
# Copy the server plus every omni_* module it names on a line starting with "import omni_..." or
# "from omni_..." (lazy imports are named in packaging hint strings: omni_lpe, omni_omnimind,
# omni_node_core + omni_node_words). Copied modules are scanned too, so their omni_* imports come along.
SRC="$TMP/daemon/Admin"
cp "$SRC/omni_live_daemon_server.py" "$DEST/omni_live_daemon_server.py"
echo omni_live_daemon_server.py > "$DEST/DAEMON_FILES"
TODO="omni_live_daemon_server"
SEEN=" omni_live_daemon_server "
while [ -n "$TODO" ]; do
  NEXT=""
  for f in $TODO; do
    for m in $(grep -ohE '^(import|from) omni_[a-z0-9_]+' "$SRC/$f.py" | awk '{print $2}' | sort -u); do
      case "$SEEN" in *" $m "*) continue ;; esac
      SEEN="$SEEN$m "
      if [ -f "$SRC/$m.py" ]; then
        cp "$SRC/$m.py" "$DEST/$m.py"
        echo "$m.py" >> "$DEST/DAEMON_FILES"
        NEXT="$NEXT $m"
      fi
    done
  done
  TODO="$NEXT"
done
echo "packaged: $(tr '\n' ' ' < "$DEST/DAEMON_FILES")"
for need in omni_node_core.py omni_node_words.py; do
  grep -qx "$need" "$DEST/DAEMON_FILES" || { echo "::error::$need was not packaged (daemon ref $REF older than v8.27.0?)"; exit 1; }
done
echo "$REF $(git -C "$TMP/daemon" rev-parse --short HEAD)" > "$DEST/DAEMON_REF"
# The single Omni Node version (repo VERSION), the same one the desktop zips carry.
tr -d ' \r\n' < "$ROOT/VERSION" > "$DEST/NODE_VERSION"
printf '# Generated by scripts/fetch_daemon.sh from VERSION. Do not edit.\nVERSION = "%s"\n' "$(cat "$DEST/NODE_VERSION")" \
  > "$DEST/omni_node_version.py"
echo "Omni Node $(cat "$DEST/NODE_VERSION")"
grep -m1 '^VERSION = ' "$DEST/omni_live_daemon_server.py"
rm -rf "$TMP"
